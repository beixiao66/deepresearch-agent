DOC_01 = """# RAG 检索增强生成：入门指南

## 什么是 RAG

RAG（Retrieval-Augmented Generation，检索增强生成）是一种结合检索与生成的大模型应用范式。
它的核心思想是：在让大语言模型生成回答之前，先从外部知识库中检索与问题相关的资料，
再把检索到的资料作为上下文提供给模型，让模型基于这些资料生成有据可依的回答。
RAG 这个名字最早由 Facebook AI Research 在 2020 年的论文《Retrieval-Augmented Generation for Knowledge-Intensive NLP Tasks》中提出。

## 为什么需要 RAG

大语言模型存在两个主要问题：一是训练数据有截止时间，无法知道最新信息；
二是幻觉问题，模型可能生成看似合理但实际错误的内容。
RAG 通过引入外部知识库，让模型回答问题时可以参考真实资料，从而：
- 缓解幻觉，提升回答可信度
- 支持回答最新信息，解决训练数据截止时间问题
- 让模型可以回答企业内部私有知识，而不需要重新训练或微调

## RAG 与微调（Fine-tuning）的对比

微调需要准备大量标注数据、消耗大量训练算力，而且模型知识更新困难。
RAG 不需要训练模型，只改检索数据，知识更新只需更换文档。
两种方案的适用场景不同：需要改变模型行为风格用微调，需要注入事实知识用 RAG。

## RAG 的完整流程

RAG 的完整流程分为两个阶段。

### 索引阶段

1. 文档加载：用 Document Loaders 把 PDF、Word、网页等原始文档读入系统。
   LangChain 提供了多种文档加载器，如 PyPDFLoader、TextLoader、DirectoryLoader。
2. 文本切分：把长文档切成适合检索的小块（chunk）。
   LangChain 常用的切分器是 RecursiveCharacterTextSplitter，按递归分隔符切分。
3. 向量化：用 Embedding 模型把文本块转换成向量。
4. 存储：把向量存入向量数据库，常见的有 Qdrant、Milvus、FAISS、Chroma。

### 检索与生成阶段

1. 用户提问
2. 把问题向量化，在向量库中检索最相似的文本块
3. 把检索到的文本块作为上下文，与问题一起发给大模型
4. 大模型基于上下文生成回答

## 总结

RAG 是一种低成本、高可控性的增强方案，不需要微调模型就能让模型掌握新知识。
常见的技术栈组合是 LangChain + 向量数据库 + 大模型 API。
"""

DOC_02 = """# RAG 进阶：文本切块与检索质量优化

## 文本切块（Chunking）的重要性

RAG 的效果很大程度上取决于文本切块的质量。切块是把长文档切分为适合检索的小片段，
这个步骤直接决定了检索到的内容是否精确。

## 切块大小怎么选

- 切块太小：语义不完整，检索到的内容信息量不足，模型无法回答
- 切块太大：混入太多无关内容，检索精度下降，还浪费大模型的上下文空间

常见的切块大小在 300 到 800 个字符之间，具体要根据文档类型和问题类型调整。
对于技术文档，通常建议 400-600 字符；对于新闻报道，可以适当调大。
在 LangChain 中可以用 RecursiveCharacterTextSplitter 配置：
chunk_size=500 表示每块约 500 字符，chunk_overlap=50 表示相邻块重叠 50 字符。
重叠可以避免关键信息恰好被切在边界上，常见的重叠大小是切块大小的 10% 到 20%。

## 混合检索

单靠向量检索（语义检索）不够，还需要关键词检索作为补充。

### 向量检索（稠密检索）

向量检索擅长理解语义：即使查询词和文档用词不同，也能找到相关内容。
比如问「大模型胡说八道」能匹配到讲「幻觉」的文档。
向量检索用的是双塔模型架构：查询和文档分别编码成向量，计算相似度。

### 关键词检索（稀疏检索）

关键词检索（如 BM25）擅长精确匹配：型号、专有名词、错误码等场景，
向量检索可能因为语义漂移而漏掉，但关键词检索一定命中。
BM25 是经典的关键词打分算法，在 SQLite 中通过 FTS5 的 bm25() 函数实现，
bm25() 返回负分，分数越低越相关，使用时取负号变成越高越相关。

### RRF 融合

RRF（Reciprocal Rank Fusion，倒数排名融合）把向量检索和关键词检索的结果按排名融合，
不需要统一两路分数，只看排名。融合公式是每个结果在所有检索路中
1/(k+rank) 的累加，经验常数 k=60。
融合后的结果兼顾语义和关键词。

### Rerank 精排

融合后的候选再交给重排模型（交叉编码器）精排。
交叉编码器把查询和文档拼接成一个序列同时编码，精度高但速度慢，
所以只用于重排精排阶段，把最相关的结果排到最前面。
实际工程中通常先召回 20-30 条候选，再用交叉编码器精排，只取 Top 5 送入大模型。
"""

