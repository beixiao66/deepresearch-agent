DOC_09 = """# 向量数据库原理与实践

## 为什么需要向量数据库

大模型应用里，文本、图片、音视频都要转成向量（Embedding）才能被检索。
普通关系数据库无法高效检索高维向量，向量数据库应运而生。

## 核心概念

### 向量与维度

文本被 Embedding 模型转换成一个浮点数数组，数组长度就是维度。
常见维度：OpenAI 的 text-embedding-3-small 是 1536 维，阿里云百炼的
text-embedding-v4 是 1024 维。维度越高表达力越强，但存储和计算成本越大。

### 向量相似度

两个向量越接近，语义越相近。衡量相似度有三种常见方式：
- 余弦相似度（Cosine）：只看方向不看长度，文本检索最常用。
  Qdrant 中用 Distance.COSINE 指定
- 欧氏距离（Euclidean）：看绝对距离，对应 Distance.EUCLID
- 内积（Dot Product）：适合归一化后的向量，对应 Distance.DOT

## 索引与检索

### 暴力检索（Brute Force）

逐个计算所有向量与查询向量的相似度，取最相似的 Top-K。
准确但慢：数据量 100 万时每次检索要算 100 万次相似度。

### 近似最近邻（ANN）

用索引结构跳过大部分不相关的向量，牺牲一点精度换取速度：
- HNSW：图结构索引，检索快、精度高，内存占用大，适合亿级以下
- IVF：聚类分桶，先把向量聚类成桶，检索时先找最近的桶再精搜
- PQ：向量压缩，把向量量化成短码，减少存储和计算

## Qdrant 实践

Qdrant 是 Rust 写的开源向量数据库，支持 Docker 部署。
用 qdrant-client 接入：创建 collection 时要指定向量维度，
写入用 upsert（PointStruct 包含 id、vector、payload），
查询用 query_points，返回点 id、score 和 payload。
"""

